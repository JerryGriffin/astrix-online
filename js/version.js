// 版本号与更新日志的唯一来源（Astrix）
//
// ============================================================================
// 为什么要单独一个文件
// ============================================================================
// v0.0.3 之前版本号硬编码在 js/ui/start.js 里，更新日志也散在同一个函数内。
// 结果出现两个问题：
//   1. 改版本号要翻 UI 文件，容易漏；
//   2. 浏览器缓存了旧的 start.js，网页上一直显示 v0.0.1。
// 现在：版本号只在这里定义一次，任何地方要显示都从这里取；
// index.html 的入口脚本带 ?v= 查询串（与 VERSION 同步），改版本号即自动击穿缓存。
//
// v0.4.22：更新日志（VERSIONS）已迁到 js/data/changelog.js 并按需加载 ——
//   本文件被 40 个模块与 cloud.js 引用，必须保持「几 KB」；日志 150 KB 留在
//   这里等于让每个玩家开机就下载全部历史更新说明。

export const VERSION = 'v0.4.22';

// 版本号数字形式（用于存档迁移判断）
export const VERSION_NUM = 62;   // v0.4.10 → 50（十位进位，见 selfcheck_v005 的版本号一致性断言）

export const VERSION_DATE = '2026-10-28';

// ============================================================================
// 修订号与缓存击穿标记
// ============================================================================
// 设计者有时会要求「版本不变，只改内容」。但 index.html 的 css / main.js 带着
// ?v= 查询串，只要这个串不变，浏览器就会继续吃缓存、玩家根本拿不到新代码。
// 所以把「对外显示的版本号」与「缓存击穿用的串」拆开：
//   VERSION     —— 玩家看到的版本（设计者说不变就不变）
//   REVISION    —— 只要改了 css/ 或 js/，这里就 +1
//   CACHE_TAG   —— 实际写进 index.html 的 ?v= 串
export const REVISION = 13;
// index.html 里所有 css 链接与 js/main.js 入口都用它；改代码后记得 +1
export const CACHE_TAG = VERSION_NUM + '.' + REVISION;

// ============================================================================
// 更新日志已拆到 js/data/changelog.js（v0.4.22）
// ============================================================================
// 原因：VERSIONS 有 1400+ 行、gzip 后 64 KB，占全部 JS 压缩体积的 11.7%，
//   而它只有一个使用点（start.js 渲染更新日志面板）。本文件被 40 个模块和
//   cloud.js 引用，必须保持「几 KB 级」；把日志留在主链路上等于让玩家
//   开机就下载全部历史更新说明。
// 现在：需要日志的地方动态加载 ——
//   const { VERSIONS } = await import(`../data/changelog.js?v=${CACHE_TAG}`);
// 注意：动态 import 用模板串拼 ?v=，不要写成裸字符串字面量，
//   否则 bump_imports.mjs 会把它改写成某一版固定串（静态正则无法感知运行时变量）。
